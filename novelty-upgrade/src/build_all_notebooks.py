        "print(\"Logistic regression:\", {k: v for k, v in results[\"logistic_regression\"].items() if \"ci\" not in k})\n"
        "\n"
        "# -- Small MLP fusion classifier (matches verifier_model.py's FusionMLP shape) --\n"
        "# Runs on CPU fine (just slower); the third arm of the 3-way comparison this\n"
        "# notebook's own title promises -- was previously left as a \"run this yourself\"\n"
        "# suggestion instead of actually run, which meant the notebook only produced 2\n"
