"""
Shared notebook-generation helper. Every 0X_*.ipynb in novelty-upgrade/notebooks/ is
generated by a build_0X_*.py script that imports this module, so all notebooks share:
  - the same cell-construction helpers (code/md),
  - the same compile-check before writing (a broken cell fails loudly here, at
    generation time, not silently when you run it on Kaggle),
  - the same Kaggle-vs-local path/detection pattern (ON_KAGGLE via env var, not
    path existence -- see 09_dpo_training.ipynb's comment for why the naive
    Path('/kaggle/...').exists() check is unsafe on Windows).

Nothing in src/ is executed against the real project data by these generator scripts
-- they only assemble and syntax-check notebook JSON. The notebooks themselves are
meant to be run on Kaggle, not locally.
"""
import ast
import json
from pathlib import Path


def code(src: str) -> dict:
    return {"cell_type": "code", "execution_count": None, "metadata": {},
            "outputs": [], "source": src.splitlines(keepends=True)}


def md(src: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": src.splitlines(keepends=True)}


